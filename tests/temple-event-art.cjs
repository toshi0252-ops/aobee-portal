const assert=require('node:assert/strict');
const {boot}=require('./temple-chapter1-flow.cjs');
const g=boot(),{run,el,flush}=g;
run("$('begin').onclick()");flush();
const before=run('JSON.stringify(snapshot())');
run('readAnnexMural()');
assert.equal(el('eventStill').hidden,false);
assert.equal(el('eventStillImage').dataset.scene,'mural');
assert.match(el('eventStillImage').src,/ch1-mural.webp$/);
run('move(1,0)');assert.equal(run('JSON.stringify(snapshot())'),before,'art/dialogue does not move player or change saved progress');
run('nextLine()');assert.equal(el('eventStill').hidden,false);
const lateLoad=el('eventStillImage').onload;
flush();assert.equal(el('eventStill').hidden,true);
run("say([['村人','こんにちは']])");lateLoad();assert.equal(el('eventStill').hidden,true,'late image load must not reopen an earlier scene');
run("say([['語り','次の場面']],null,'homecoming')");
assert.equal(el('eventStill').hidden,true,'queued scene waits for active dialogue');
run('nextLine()');assert.equal(el('eventStillImage').dataset.scene,'homecoming');
assert.equal(el('eventStill').hidden,false);
el('eventStillImage').onerror();assert.equal(el('eventStill').hidden,true,'missing art keeps dialogue playable');
flush();assert.equal(run('pendingDialogues.length'),0);
run('reportChapter1()');assert.equal(el('eventStillImage').dataset.scene,'homecoming');
assert.equal(run('chapter1Story.reportSeen'),false,'chapter waits for player to finish dialogue');
flush();assert.equal(el('eventStill').hidden,true);assert.equal(run('chapter1Story.reportSeen'),true);
assert.equal(el('chapterClear').hidden,false);
console.log('PASS both event cues, pause/progress preservation, dialogue completion, queued scenes, late loading, missing-image fallback and chapter-clear handoff');
